"""
generate_add_cities_sql.py

Turns a cities CSV (worldcities columns) plus its fetched climate CSV into one
SQL file that adds those cities to the live seventy_two schema, including the
region/sub_region columns the climate table gained after generate_sql.py.

Also appends the cities to worldcities_enriched.csv and climate_all_500.csv so
generate_location_index.py and generate_advisories.py pick them up.

USAGE:
  cd /home/ram/projects/72somewhere
  uv run data/scripts/generate_add_cities_sql.py data/worldcities_travel30.csv \
      data/climate_data_worldcities_travel30.csv
  # then run the printed .sql file in the Supabase SQL Editor
"""

import csv
import os
import sys

from generate_sql import sql_num, sql_str

DATA_DIR = os.path.join(os.path.dirname(__file__), "..")
ENRICHED_CSV = os.path.join(DATA_DIR, "worldcities_enriched.csv")
CLIMATE_MERGED_CSV = os.path.join(DATA_DIR, "climate_all_500.csv")


def main(cities_csv, climate_csv):
    with open(cities_csv, encoding="utf-8") as f:
        cities = list(csv.DictReader(f))
    with open(climate_csv, encoding="utf-8") as f:
        climate = list(csv.DictReader(f))

    # Region comes from existing cities in the same country
    with open(ENRICHED_CSV, encoding="utf-8") as f:
        enriched_fields = csv.DictReader(f).fieldnames
        f.seek(0)
        enriched = list(csv.DictReader(f))
    regions = {}
    for row in enriched:
        regions.setdefault(row["country"], (row["region"], row["sub_region"], row["intermediate_region"]))
    enriched_ids = {row["id"] for row in enriched}

    missing_region = sorted({c["country"] for c in cities} - regions.keys())
    if missing_region:
        sys.exit(f"ERROR: no region known for {missing_region}")

    by_city = {}
    for row in climate:
        by_city.setdefault(row["city_id"], []).append(row)
    incomplete = [c["city_ascii"] for c in cities if len(by_city.get(c["id"], [])) != 12]
    if incomplete:
        sys.exit(f"ERROR: climate data missing or incomplete (need 12 months) for {incomplete}")

    city_rows = [
        f"({sql_str(c['id'])}, {sql_str(c['city'])}, {sql_str(c['city_ascii'])}, {c['lat']}, {c['lng']}, "
        f"{sql_str(c['country'])}, {sql_str(c['iso2'])}, {sql_str(c['iso3'])}, {sql_str(c['admin_name'])}, "
        f"{sql_str(c['capital'])}, {sql_num(c['population'])})"
        for c in cities
    ]
    climate_rows = []
    for c in cities:
        region, sub_region, _ = regions[c["country"]]
        for m in sorted(by_city[c["id"]], key=lambda r: int(r["month"])):
            climate_rows.append(
                f"({sql_str(m['city_id'])}, {sql_str(m['city_name'])}, {sql_str(m['country'])}, {m['month']}, "
                f"{m['avg_high_temp_c']}, {m['avg_low_temp_c']}, {m['avg_precip_mm']}, "
                f"{sql_str(region)}, {sql_str(sub_region)})"
            )

    name = os.path.splitext(os.path.basename(cities_csv))[0]
    sql_path = os.path.join(DATA_DIR, "sql", f"add_{name}.sql")
    with open(sql_path, "w", encoding="utf-8") as f:
        f.write(f"-- Adds {len(cities)} cities from {os.path.basename(cities_csv)} — generated by generate_add_cities_sql.py\n")
        f.write("-- Safe to re-run: ON CONFLICT DO NOTHING\n\n")
        f.write("INSERT INTO seventy_two.cities (id, city, city_ascii, lat, lng, country, iso2, iso3, admin_name, capital, population)\nVALUES\n  ")
        f.write(",\n  ".join(city_rows))
        f.write("\nON CONFLICT (id) DO NOTHING;\n\n")
        f.write("INSERT INTO seventy_two.climate (city_id, city_name, country, month, avg_high_temp_c, avg_low_temp_c, avg_precip_mm, region, sub_region)\nVALUES\n  ")
        f.write(",\n  ".join(climate_rows))
        f.write("\nON CONFLICT (city_id, month) DO NOTHING;\n")

    # Keep local copies in sync (skip rows already present so re-runs are safe)
    new_cities = [c for c in cities if c["id"] not in enriched_ids]
    with open(ENRICHED_CSV, "a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=enriched_fields, extrasaction="ignore")
        for c in new_cities:
            region, sub_region, intermediate = regions[c["country"]]
            writer.writerow({**c, "region": region, "sub_region": sub_region, "intermediate_region": intermediate})

    with open(CLIMATE_MERGED_CSV, encoding="utf-8") as f:
        merged_ids = {row["city_id"] for row in csv.DictReader(f)}
    fieldnames = ["city_id", "city_name", "country", "month", "avg_high_temp_c", "avg_low_temp_c", "avg_precip_mm"]
    with open(CLIMATE_MERGED_CSV, "a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        for c in cities:
            if c["id"] not in merged_ids:
                writer.writerows(sorted(by_city[c["id"]], key=lambda r: int(r["month"])))

    print(f"Wrote {sql_path}: {len(city_rows)} cities, {len(climate_rows)} climate rows")
    print(f"Appended {len(new_cities)} cities to worldcities_enriched.csv and climate_all_500.csv")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
