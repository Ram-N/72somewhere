"""
Generate Supabase INSERT SQL files from CSV data.

Outputs:
  data/sql/cities_insert.sql   — ~510 INSERT statements for cities table
  data/sql/climate_insert.sql  — ~6,000 INSERT statements for climate table
  data/climate_all_500.csv     — merged climate data (all batches combined)
"""

import csv
import glob
import os

# Paths relative to repo root
REPO_ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
DATA_DIR = os.path.join(REPO_ROOT, "data")
SQL_DIR = os.path.join(DATA_DIR, "sql")
CITIES_CSV = os.path.join(DATA_DIR, "worldcities_top500.csv")
CLIMATE_MERGED_CSV = os.path.join(DATA_DIR, "climate_all_500.csv")
CITIES_SQL = os.path.join(SQL_DIR, "cities_insert.sql")
CLIMATE_SQL = os.path.join(SQL_DIR, "climate_insert.sql")

CHUNK_SIZE = 500  # rows per INSERT statement


def esc(s):
    """Escape single quotes for SQL strings."""
    return s.replace("'", "''")


def sql_str(val):
    """Return SQL NULL or a quoted string."""
    if val is None or str(val).strip() == "":
        return "NULL"
    return f"'{esc(str(val).strip())}'"


def sql_num(val):
    """Return SQL NULL or a numeric literal."""
    if val is None or str(val).strip() == "":
        return "NULL"
    try:
        f = float(val)
        # Return integer if whole number, else float
        return str(int(f)) if f == int(f) else str(f)
    except (ValueError, TypeError):
        return "NULL"


def write_chunks(f, table, columns, rows, conflict_clause):
    """Write rows in CHUNK_SIZE batches as INSERT statements."""
    for i in range(0, len(rows), CHUNK_SIZE):
        chunk = rows[i : i + CHUNK_SIZE]
        values_str = ",\n  ".join(chunk)
        f.write(f"INSERT INTO {table} ({columns})\nVALUES\n  {values_str}\n{conflict_clause};\n\n")


def generate_cities_sql():
    rows = []
    with open(CITIES_CSV, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            city_id = sql_str(row["id"])
            city = sql_str(row["city"])
            city_ascii = sql_str(row["city_ascii"])
            lat = row["lat"]
            lng = row["lng"]
            country = sql_str(row["country"])
            iso2 = sql_str(row.get("iso2", ""))
            iso3 = sql_str(row.get("iso3", ""))
            admin_name = sql_str(row.get("admin_name", ""))
            capital = sql_str(row.get("capital", ""))
            population = sql_num(row.get("population", ""))
            rows.append(
                f"({city_id}, {city}, {city_ascii}, {lat}, {lng}, {country}, "
                f"{iso2}, {iso3}, {admin_name}, {capital}, {population})"
            )

    columns = "id, city, city_ascii, lat, lng, country, iso2, iso3, admin_name, capital, population"
    os.makedirs(SQL_DIR, exist_ok=True)
    with open(CITIES_SQL, "w", encoding="utf-8") as f:
        f.write("-- Cities INSERT — generated by generate_sql.py\n")
        f.write("-- Safe to re-run: ON CONFLICT DO NOTHING\n\n")
        write_chunks(f, "cities", columns, rows, "ON CONFLICT (id) DO NOTHING")

    print(f"cities_insert.sql: {len(rows)} rows written")
    return len(rows)


def generate_climate_sql():
    pattern = os.path.join(DATA_DIR, "climate_data_top500_mini_batch_*.csv")
    batch_files = sorted(glob.glob(pattern))
    if not batch_files:
        print("ERROR: No climate batch files found.")
        return 0

    all_rows_raw = []
    seen = set()

    for filepath in batch_files:
        with open(filepath, newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                key = (row["city_id"], row["month"])
                if key in seen:
                    continue
                seen.add(key)
                all_rows_raw.append(row)

    # Write merged CSV
    if all_rows_raw:
        fieldnames = ["city_id", "city_name", "country", "month",
                      "avg_high_temp_c", "avg_low_temp_c", "avg_precip_mm"]
        with open(CLIMATE_MERGED_CSV, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
            writer.writeheader()
            writer.writerows(all_rows_raw)
        print(f"climate_all_500.csv: {len(all_rows_raw)} rows written")

    # Build SQL value tuples
    sql_rows = []
    for row in all_rows_raw:
        city_id = sql_str(row["city_id"])
        city_name = sql_str(row["city_name"])
        country = sql_str(row["country"])
        month = row["month"]
        high = row["avg_high_temp_c"]
        low = row["avg_low_temp_c"]
        precip = row["avg_precip_mm"]
        sql_rows.append(f"({city_id}, {city_name}, {country}, {month}, {high}, {low}, {precip})")

    columns = "city_id, city_name, country, month, avg_high_temp_c, avg_low_temp_c, avg_precip_mm"
    with open(CLIMATE_SQL, "w", encoding="utf-8") as f:
        f.write("-- Climate INSERT — generated by generate_sql.py\n")
        f.write(f"-- {len(batch_files)} batch files merged, {len(sql_rows)} rows total\n")
        f.write("-- Safe to re-run: ON CONFLICT DO NOTHING\n\n")
        write_chunks(f, "climate", columns, sql_rows, "ON CONFLICT (city_id, month) DO NOTHING")

    print(f"climate_insert.sql: {len(sql_rows)} rows written ({len(batch_files)} batch files)")
    return len(sql_rows)


if __name__ == "__main__":
    print("Generating SQL insert files...\n")
    city_count = generate_cities_sql()
    climate_count = generate_climate_sql()
    print(f"\nDone. Output files:")
    print(f"  data/sql/cities_insert.sql  ({city_count} rows)")
    print(f"  data/sql/climate_insert.sql ({climate_count} rows)")
    print(f"  data/climate_all_500.csv    ({climate_count} rows)")
